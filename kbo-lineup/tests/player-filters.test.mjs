import assert from 'node:assert/strict';
import fs from 'node:fs';
import {EMPTY_FILTERS,filterPlayers,unassignedPlayers} from '../app/player-filters.js';
import {overall} from '../app/manager-engine.js';
const db=JSON.parse(fs.readFileSync(new URL('../data/catalog.json',import.meta.url)));
const thames=db.find(c=>c.name==='테임즈'&&c.year===2015);
assert.ok(thames?.positions.includes('1B'));
const a={...thames,grade:'LEGEND',uniqueId:'active-thames'},same={...thames,year:2014,grade:'PLATINUM',uniqueId:'same-person'};
const base=db.find(c=>c.pos==='1B'&&c.playerId!==a.playerId),backup={...base,grade:'PLATINUM',uniqueId:'backup-1b'};
const outfielder={...db.find(c=>c.pos==='RF'&&!c.positions.includes('1B')),grade:'HERO',uniqueId:'backup-rf'};
const pitcher={...db.find(c=>c.pos==='P'),grade:'LEGEND',uniqueId:'pitcher'};
const players=[a,same,backup,outfielder,pitcher];
const bench=unassignedPlayers(players,{'1B':a},{starters:['pitcher'],relief:[]});
assert.deepEqual(bench.map(c=>c.uniqueId),['backup-1b','backup-rf']);
assert.deepEqual(filterPlayers(bench,EMPTY_FILTERS,'1B').map(c=>c.uniqueId),['backup-1b']);
assert.deepEqual(filterPlayers(bench,{...EMPTY_FILTERS,position:'RF'},'1B').map(c=>c.uniqueId),['backup-1b']);
const filters={...EMPTY_FILTERS,query:backup.name,grade:'PLATINUM',position:'1B',team:backup.team,minOvr:String(overall(backup))};
assert.deepEqual(filterPlayers(players,filters).map(c=>c.uniqueId),['backup-1b']);
assert.equal(filterPlayers(players,{...filters,minOvr:String(overall(backup)+1)}).length,0);
assert.equal(filterPlayers([{...backup,ovr:999}],{...EMPTY_FILTERS,minOvr:'100'}).length,0);
assert.equal(filterPlayers(players,{...filters,grade:'SIGNATURE'}).length,0);
assert.equal(filterPlayers(bench,{...EMPTY_FILTERS,minOvr:''}).length,2);
const order=players.map(c=>c.uniqueId);const sorted=filterPlayers(players,{...EMPTY_FILTERS,sort:'ovr-desc'});assert.ok(sorted.every((c,i)=>!i||overall(sorted[i-1])>=overall(c)));assert.deepEqual(players.map(c=>c.uniqueId),order);
console.log('PASS: assigned Thames and other seasons excluded, real backup 1B kept, locked-position eligibility, combined grade/position/name/team/OVR filters, inclusive OVR and non-mutating sort');
